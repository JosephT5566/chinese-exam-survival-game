export function icon(name: string) {
  const rows = glyphs[name] ?? glyphs.book!;
  return (
    '<span aria-hidden="true" class="pixel-icon" style="--rows:' +
    rows.length +
    '">' +
    rows
      .flatMap((row, y) =>
        [...row].flatMap((v, x) =>
          v === "1"
            ? ['<i style="grid-area:' + (y + 1) + "/" + (x + 1) + '"></i>']
            : [],
        ),
      )
      .join("") +
    "</span>"
  );
}
