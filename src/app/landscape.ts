// Original 320 × 136 pixel landscape. All scenery uses integer coordinates.
export function paintLandscape(canvas: HTMLCanvasElement) {
  const g = canvas.getContext("2d");
  if (!g) return;
  const w = (canvas.width = 320),
    h = (canvas.height = 136);
  function rect(
    x: number,
    y: number,
    width: number,
    height: number,
    color: string,
  ) {
    g!.fillStyle = color;
    g!.fillRect(x, y, width, height);
  }
  function shape(points: number[][], color: string) {
    // Scanline fill preserves hard pixel edges along the stepped silhouettes.
    for (let y = 0; y < h; y++) {
      const cuts: number[] = [];
      for (let i = 0; i < points.length; i++) {
        const [x1, y1] = points[i]!,
          [x2, y2] = points[(i + 1) % points.length]!;
        if ((y1! <= y && y2! > y) || (y2! <= y && y1! > y))
          cuts.push(x1! + ((y - y1!) * (x2! - x1!)) / (y2! - y1!));
      }
      cuts.sort((a, b) => a - b);
      for (let i = 0; i + 1 < cuts.length; i += 2)
        rect(
          Math.round(cuts[i]!),
          y,
          Math.round(cuts[i + 1]!) - Math.round(cuts[i]!),
          1,
          color,
        );
    }
  }
  rect(0, 0, w, h, "#f3ddb1");
  for (let y = -13; y <= 13; y++) {
    const span = Math.floor(Math.sqrt(169 - y * y));
    rect(249 - span, 22 + y, span * 2, 1, "#ef9e57");
  }
  for (const [x, y, l] of [
    [2, 18, 20],
    [49, 10, 18],
    [136, 14, 15],
    [186, 26, 20],
    [260, 33, 31],
    [92, 31, 15],
  ]) {
    rect(x!, y!, l!, 2, "#fff0ca");
    rect(x! + 5, y! - 2, l! - 9, 2, "#fff0ca");
  }
  shape(
    [
      [0, 45],
      [21, 42],
      [39, 28],
      [56, 44],
      [68, 37],
      [94, 52],
      [126, 24],
      [140, 29],
      [151, 18],
      [178, 42],
      [189, 37],
      [214, 54],
      [244, 32],
      [253, 37],
      [278, 18],
      [306, 41],
      [320, 33],
      [320, 110],
      [0, 110],
    ],
    "#acb798",
  );
  shape(
    [
      [0, 63],
      [35, 44],
      [51, 51],
      [65, 39],
      [86, 56],
      [106, 45],
      [125, 66],
      [145, 51],
      [165, 58],
      [191, 37],
      [217, 52],
      [230, 47],
      [255, 61],
      [279, 44],
      [304, 56],
      [320, 50],
      [320, 110],
      [0, 110],
    ],
    "#799982",
  );
  shape(
    [
      [0, 61],
      [23, 53],
      [46, 63],
      [62, 61],
      [83, 72],
      [112, 62],
      [130, 72],
      [153, 65],
      [177, 69],
      [203, 58],
      [222, 66],
      [244, 61],
      [259, 72],
      [286, 64],
      [320, 69],
      [320, 118],
      [0, 118],
    ],
    "#4f7b6e",
  );
  rect(0, 75, 320, 61, "#84ab94");
  shape(
    [
      [0, 72],
      [41, 78],
      [77, 76],
      [106, 83],
      [146, 80],
      [178, 87],
      [229, 82],
      [262, 88],
      [320, 77],
      [320, 87],
      [265, 95],
      [219, 92],
      [174, 100],
      [149, 94],
      [103, 98],
      [75, 91],
      [37, 93],
      [0, 90],
    ],
    "#b8c6a0",
  );
  shape(
    [
      [0, 83],
      [29, 87],
      [64, 86],
      [93, 90],
      [136, 88],
      [169, 94],
      [202, 90],
      [240, 94],
      [269, 89],
      [320, 92],
      [320, 136],
      [0, 136],
    ],
    "#69926b",
  );
  shape(
    [
      [0, 107],
      [52, 95],
      [89, 102],
      [137, 94],
      [167, 104],
      [195, 97],
      [223, 100],
      [260, 96],
      [291, 99],
      [320, 91],
      [320, 136],
      [0, 136],
    ],
    "#426e55",
  );
  shape(
    [
      [213, 81],
      [216, 81],
      [208, 86],
      [190, 91],
      [187, 93],
      [220, 96],
      [225, 99],
      [220, 102],
      [152, 109],
      [139, 113],
      [146, 116],
      [177, 120],
      [184, 124],
      [169, 129],
      [154, 136],
      [124, 136],
      [151, 126],
      [158, 123],
      [135, 120],
      [125, 116],
      [127, 111],
      [143, 106],
      [208, 99],
      [183, 95],
      [183, 91],
    ],
    "#ddbd7d",
  );
  function pine(x: number, y: number, s: number) {
    rect(x - s, y - 3 * s, 2 * s, 4 * s, "#374e42");
    for (const [dy, width] of [
      [-11, 2],
      [-9, 4],
      [-7, 6],
      [-5, 8],
      [-3, 10],
    ]) {
      rect(x - (width! * s) / 2, y + dy! * s, width! * s, 2 * s, "#244e43");
      rect(
        x - (width! * s) / 2,
        y + dy! * s,
        Math.max(1, ((width! * s) / 3) | 0),
        s,
        "#527e5e",
      );
    }
  }
  for (const [x, y, s] of [
    [2, 103, 3],
    [13, 98, 2],
    [26, 94, 2],
    [43, 88, 1],
    [57, 91, 1],
    [71, 94, 1],
    [103, 88, 1],
    [112, 89, 1],
    [242, 91, 1],
    [254, 94, 2],
    [266, 98, 2],
    [282, 99, 3],
    [301, 108, 3],
    [319, 113, 4],
    [9, 130, 4],
    [28, 135, 3],
    [49, 126, 2],
    [83, 115, 1],
    [263, 123, 2],
    [288, 138, 3],
    [317, 136, 4],
  ])
    pine(x!, y!, s!);
  // A tiled pavilion above the pass.
  rect(200, 72, 24, 3, "#435746");
  rect(204, 65, 3, 7, "#925c40");
  rect(218, 65, 3, 7, "#925c40");
  shape(
    [
      [196, 65],
      [199, 65],
      [205, 61],
      [211, 58],
      [214, 58],
      [221, 62],
      [227, 63],
      [230, 61],
      [228, 66],
      [198, 67],
    ],
    "#334f43",
  );
  rect(204, 64, 17, 1, "#bb8052");
  rect(211, 56, 3, 3, "#334f43");
  // Traveller with a straw hat, satchel and walking stick.
  rect(155, 112, 3, 5, "#263c34");
  rect(160, 112, 3, 5, "#263c34");
  rect(152, 116, 6, 2, "#273f35");
  rect(160, 116, 5, 2, "#273f35");
  rect(153, 103, 9, 10, "#a75035");
  rect(154, 103, 3, 7, "#db8153");
  rect(161, 106, 4, 2, "#e3b57b");
  rect(165, 102, 1, 16, "#5c4936");
  rect(155, 98, 7, 5, "#edc393");
  rect(155, 98, 2, 5, "#544331");
  rect(150, 97, 15, 2, "#694f35");
  rect(152, 95, 11, 2, "#d6a45a");
  rect(155, 93, 6, 2, "#e5bb71");
  for (let i = 0; i < 96; i++) {
    const x = (i * 103 + 19) % 320,
      y = 104 + ((i * 17) % 31);
    if (x < 112 || x > 190) rect(x, y, 2, 1, i % 3 ? "#749365" : "#dfad68");
  }
}
